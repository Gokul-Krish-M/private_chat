import { c } from './colors.js';

/**
 * Private mode: turns a message into a plausible-looking code snippet.
 * The snippet is real code: running it returns the original message
 * (bytes XOR-ed with a random key). It's camouflage against shoulder-surfing,
 * not encryption.
 */
export const LANGS = ['js', 'py', 'go'];

const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
const tag = () => Math.floor(Math.random() * 0xfff).toString(16).padStart(3, '0');

function encode(text) {
  const key = 1 + Math.floor(Math.random() * 254);
  const hex = (n) => '0x' + n.toString(16).padStart(2, '0');
  const bytes = [...Buffer.from(text, 'utf8')].map((b) => hex(b ^ key));
  const rows = [];
  for (let i = 0; i < bytes.length; i += 10) rows.push(bytes.slice(i, i + 10).join(', ') + ',');
  return { key: hex(key), rows };
}

const templates = {
  js({ key, rows }) {
    const id = `${pick(['cfg', 'chunk', 'seg', 'blk', 'node'])}_${tag()}`;
    const fn = pick(['resolve', 'hydrate', 'unpack', 'loadConfig', 'parseChunk']);
    return [
      '// Code generated by build. DO NOT EDIT.',
      `const ${id} = Object.freeze({`,
      `  seed: ${key},`,
      '  data: [',
      ...rows.map((r) => `    ${r}`),
      '  ],',
      '});',
      `export const ${fn} = () =>`,
      `  Buffer.from(${id}.data.map((b) => b ^ ${id}.seed)).toString('utf8');`,
    ].join('\n');
  },

  py({ key, rows }) {
    const id = `${pick(['CFG', 'CHUNK', 'SEG', 'BLOCK'])}_${tag().toUpperCase()}`;
    const fn = pick(['resolve', 'hydrate', 'unpack', 'load_config', 'parse_chunk']);
    return [
      '# auto-generated - do not edit',
      `${id}_SEED = ${key}`,
      `${id}_DATA = bytes([`,
      ...rows.map((r) => `    ${r}`),
      '])',
      '',
      `def ${fn}() -> str:`,
      `    return bytes(b ^ ${id}_SEED for b in ${id}_DATA).decode("utf-8")`,
    ].join('\n');
  },

  go({ key, rows }) {
    const id = `${pick(['cfg', 'chunk', 'seg', 'blk'])}${tag().toUpperCase()}`;
    const fn = pick(['resolve', 'hydrate', 'unpack', 'loadConfig', 'parseChunk']);
    return [
      '// Code generated by protoc. DO NOT EDIT.',
      `var ${id} = []byte{`,
      ...rows.map((r) => `\t${r}`),
      '}',
      '',
      `func ${fn}() string {`,
      `\tout := make([]byte, len(${id}))`,
      `\tfor i, b := range ${id} {`,
      `\t\tout[i] = b ^ ${key}`,
      '\t}',
      '\treturn string(out)',
      '}',
    ].join('\n');
  },
};

export function disguise(text, lang = 'js') {
  const tpl = templates[lang] ?? templates.js;
  return tpl(encode(text));
}

const TOKEN =
  /(\/\/.*$|#.*$)|('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")|(0x[0-9a-f]+)|\b(const|export|return|def|func|var|for|range|in|make|bytes|string|Object|Buffer)\b/gim;

/** Minimal syntax colouring so the snippet looks like code in an editor. */
export function highlight(code) {
  return code.replace(TOKEN, (m, comment, str, num, kw) => {
    if (comment) return c.gray(m);
    if (str) return c.green(m);
    if (num) return c.yellow(m);
    if (kw) return c.blue(m);
    return m;
  });
}
